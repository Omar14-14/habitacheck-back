CREATE TABLE propiedades (
    id_propiedad BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_arrendador BIGINT NOT NULL REFERENCES usuarios (id_usuario),
    titulo VARCHAR(150) NOT NULL CHECK (length(btrim(titulo)) > 0),
    descripcion TEXT NOT NULL CHECK (length(btrim(descripcion)) > 0),
    precio_mensual NUMERIC(12,2) NOT NULL CHECK (precio_mensual > 0),
    calle VARCHAR(150) NOT NULL,
    numero_exterior VARCHAR(20) NOT NULL,
    numero_interior VARCHAR(20),
    colonia VARCHAR(100) NOT NULL,
    municipio VARCHAR(100) NOT NULL,
    estado_ubicacion VARCHAR(100) NOT NULL,
    codigo_postal VARCHAR(5) NOT NULL CHECK (codigo_postal ~ '^[0-9]{5}$'),
    estado VARCHAR(20) NOT NULL CHECK (estado IN ('disponible', 'rentada', 'pausada', 'eliminada')),
    fecha_publicacion TIMESTAMPTZ NOT NULL
);
CREATE INDEX ix_propiedades_arrendador ON propiedades (id_arrendador);

CREATE TABLE propiedad_fotografia (
    id_fotografia BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_propiedad BIGINT NOT NULL REFERENCES propiedades (id_propiedad),
    url TEXT NOT NULL,
    orden SMALLINT NOT NULL CHECK (orden > 0),
    fecha_carga TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_propiedad_fotografia_orden UNIQUE (id_propiedad, orden)
);

CREATE TABLE servicios (
    id_servicio BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(80) NOT NULL,
    descripcion TEXT,
    estado VARCHAR(20) NOT NULL CHECK (estado IN ('activo', 'inactivo'))
);

CREATE TABLE propiedad_servicio (
    id_propiedad BIGINT NOT NULL REFERENCES propiedades (id_propiedad),
    id_servicio BIGINT NOT NULL REFERENCES servicios (id_servicio),
    PRIMARY KEY (id_propiedad, id_servicio)
);
CREATE INDEX ix_propiedad_servicio_servicio ON propiedad_servicio (id_servicio);
